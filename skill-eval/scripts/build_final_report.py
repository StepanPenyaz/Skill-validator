#!/usr/bin/env python3
"""
build_final_report.py - assembles a skill's two reports from Markdown step
reports. Markdown in, Markdown out; no JSON, no model, no Claude session.

Usage:
    python build_final_report.py <skill_dir> [--baseline <older_skill_dir>] [--out <path>]

Reads from <skill_dir>:
    SKILL.md                                      name, version, description (frontmatter)
    step_reports/01_structure.md                  structure check report
    step_reports/02_rubric.md                     rubric review report
    step_reports/04_comparison_<model>_a.md       table ROWS (| verified | produced | model | version | notes |)
    step_reports/04_comparison_<model>_b.md       and a line "Verdict: Equivalent | Minor gaps | Major gaps - reason"
                                                  from two independent judges; one file
                                                  04_comparison_<model>.md also works
    step_reports/05_similarity.md                 output of compute_similarity.py (optional)
    evals/<skill>_<version>_outputs/run_on_<model>_report.md
                                                  lines like "- Tokens used: 35120",
                                                  "- Time spent: 5m 12s", "- Total cost: $0.2107"
    evals/GENERATED.md                            present when the eval data was generated by a subagent

Writes two files:
    <skill_dir>/detailed_final_report.md          everything, numbered sections 1-9 (or --out)
    <skill_dir>/final_report.md                   short: 1 Summary, 2 Skill name, 3 Skill description,
                                                  4 Model recommendation, and 5 Blocking structure findings
                                                  when the structure check found Blockers

The model recommendation is a deterministic rule: the highest similarity per dollar, with a failed run
counted as 0 (see recommend()).

With --baseline, <older_skill_dir> must already contain a detailed_final_report.md (produced by this
script). Its tables are parsed and shown next to the current ones with V1 / V2 / delta columns, and the
summary gets three Mermaid charts (token usage, total cost, time spent).
"""

import re
import sys
from pathlib import Path

import yaml

for _stream in (sys.stdout, sys.stderr):
    if hasattr(_stream, "reconfigure"):
        _stream.reconfigure(encoding="utf-8")

RUN_HEADER = "| Model used | Number of tokens used | Time spent | Total cost |"
COMPARE_HEADER = "| Verified output | Produced output | Model | Skill version | Notes |"
SIM_SUMMARY_HEADER = "| Model | Similarity"
SIM_CASE_HEADER = "| Case | Model | Similarity"
SIM_RUN_HEADER = "| Model | Run | Similarity"
CONFIG_PATH = Path(__file__).resolve().parent.parent / "config.yaml"
VERDICTS = {"equivalent": 0, "minor gaps": 1, "disputed": 2, "major gaps": 3}
VERDICT_LABELS = {"equivalent": "Equivalent", "minor gaps": "Minor gaps", "disputed": "Disputed",
                  "major gaps": "Major gaps"}
GENERATED_NOTE = ("The inputs and verified outputs in `evals/` were generated by a subagent "
                  "(see `evals/GENERATED.md`). Review them: the similarity numbers and the recommendation are "
                  "only as good as these examples, and checked examples improve the result.")


# ---------- small helpers ----------

def read(path):
    p = Path(path)
    return p.read_text(encoding="utf-8").strip() if p.is_file() else None


def demote(text, levels=2):
    """Push Markdown headings down so an embedded report sits under a section heading."""
    out, in_fence = [], False
    for line in text.splitlines():
        if line.startswith("```"):
            in_fence = not in_fence
        if not in_fence and line.startswith("#"):
            line = "#" * levels + line
        out.append(line)
    return "\n".join(out)


def skill_meta(skill_dir):
    text = (Path(skill_dir) / "SKILL.md").read_text(encoding="utf-8")
    m = re.match(r"^---\r?\n(.*?)\r?\n---", text, re.DOTALL)
    fm = yaml.safe_load(m.group(1)) if m else {}
    meta = fm.get("metadata") or {}
    return {
        "name": str(fm.get("name") or Path(skill_dir).resolve().name),
        "version": str(meta.get("version") or "unknown"),
        "description": " ".join(str(fm.get("description") or "").split()),
    }


def fmt_tokens(n):
    return "unavailable" if n is None else f"{n:,}"


def fmt_time(s):
    if s is None:
        return "unavailable"
    s = int(round(s))
    return f"{s // 60}m {s % 60:02d}s" if s >= 60 else f"{s}s"


def fmt_cost(c):
    return "unavailable" if c is None else f"${c:,.4f}"


def fmt_pct(p):
    return "unavailable" if p is None else f"{p:.1f}%"


def parse_tokens(t):
    t = t.strip().replace(",", "")
    return int(t) if t.isdigit() else None


def parse_time(t):
    m = re.fullmatch(r"\s*(?:(\d+)m\s*)?(\d+)s\s*", t)
    return int(m.group(1) or 0) * 60 + int(m.group(2)) if m else None


def parse_cost(t):
    try:
        return float(t.strip().lstrip("$").replace(",", ""))
    except ValueError:
        return None


def parse_pct(t):
    try:
        return float(t.strip().rstrip("%"))
    except ValueError:
        return None


def delta(old, new, fmt, signed_fmt=None):
    if old is None or new is None:
        return "n/a"
    d = new - old
    sign = "+" if d > 0 else ("-" if d < 0 else "")
    pct = f" ({sign}{abs(d) / old * 100:.0f}%)" if old else ""
    return f"{sign}{fmt(abs(d))}{pct}"


def split_cells(row):
    cells = re.split(r"(?<!\\)\|", row.strip().strip("|"))
    return [c.strip().replace("\\|", "|") for c in cells]


def table_rows(section_text, header_start):
    rows, on = [], False
    for line in section_text.splitlines():
        if line.startswith(header_start):
            on = True
            continue
        if on:
            if not line.startswith("|"):
                break
            if not set(line.replace("|", "").strip()) <= set("-: "):
                rows.append(split_cells(line))
    return rows


def table_dicts(text, header_start):
    """First table whose header starts with header_start, as a list of {column name: cell}."""
    lines = text.splitlines()
    for i, line in enumerate(lines):
        if line.startswith(header_start):
            header, rows = split_cells(line), []
            for l in lines[i + 1:]:
                if not l.startswith("|"):
                    break
                if set(l.replace("|", "").strip()) <= set("-: "):
                    continue
                rows.append(dict(zip(header, split_cells(l))))
            return rows
    return []


# ---------- reading run reports ----------

def read_runs(skill_dir, meta):
    out_dir = Path(skill_dir) / "evals" / f"{meta['name']}_{meta['version']}_outputs"
    runs = {}
    for f in sorted(out_dir.glob("run_on_*_report.md")):
        fields = dict(re.findall(r"^-\s*([^:]+):\s*(.+?)\s*$", f.read_text(encoding="utf-8"), re.M))
        model = fields.get("Model name") or f.stem[len("run_on_"):-len("_report")]
        runs[model] = {
            "tokens": parse_tokens(fields.get("Tokens used", "")),
            "time": parse_time(fields.get("Time spent", "")),
            "cost": parse_cost(fields.get("Total cost", "")),
            "extra": {k: fields[k] for k in ("Runs", "Complete runs", "Failed cases", "Turns", "Tool calls",
                                              "Skill loaded", "Input tokens", "Output tokens",
                                              "Cache read tokens", "Cache creation tokens") if k in fields},
        }
    return runs


JUDGE_FILE = re.compile(r"^04_comparison_(.+?)(?:_([ab]))?\.md$")


def comparison_files(skill_dir):
    """[(model, judge letter or None, path)] of the comparison reports."""
    out = []
    for f in sorted((Path(skill_dir) / "step_reports").glob("04_comparison_*.md")):
        m = JUDGE_FILE.match(f.name)
        if m:
            out.append((m.group(1), m.group(2), f))
    return out


def read_comparison_rows(skill_dir):
    """Table rows of the comparison reports. With two judges only judge a's rows are shown."""
    rows = []
    for _model, judge, f in comparison_files(skill_dir):
        if judge == "b":
            continue
        rows += [l.strip() for l in f.read_text(encoding="utf-8").splitlines() if l.strip().startswith("|")]
    return rows


VERDICT_LINE = re.compile(r"^\W*Verdict:\s*(Equivalent|Minor gaps|Major gaps)\b\s*[-:–—]?\s*(.*)$",
                          re.M | re.I)


def combine_verdicts(items):
    """One verdict from the judges' (verdict, reason) pairs. Pure function.

    One judge: as given. Two or more: all say major -> major gaps; some say major -> disputed (the model
    is not dropped, a person must check); none -> the worse of them.
    """
    if not items:
        return None
    majors = sum(1 for v, _ in items if v == "major gaps")
    if len(items) == 1:
        verdict, reason = items[0]
    elif majors == len(items):
        verdict = "major gaps"
    elif majors:
        verdict = "disputed"
    else:
        verdict = max((v for v, _ in items), key=lambda v: VERDICTS[v])
    if len(items) > 1:
        reason = " | ".join(f"judge {i + 1} ({VERDICT_LABELS[v]}): {r}" for i, (v, r) in enumerate(items))
    return verdict, reason


def read_verdicts(skill_dir):
    """{model: (verdict, reason)} from the Verdict line of each judge's comparison report."""
    per_model = {}
    for model, _judge, f in comparison_files(skill_dir):
        m = VERDICT_LINE.search(f.read_text(encoding="utf-8"))
        if m:
            per_model.setdefault(model, []).append((m.group(1).lower(), m.group(2).strip()))
    return {model: combine_verdicts(items) for model, items in per_model.items()}


def read_similarity(skill_dir):
    """The tables and flags of step_reports/05_similarity.md (None if the step did not run)."""
    text = read(Path(skill_dir) / "step_reports" / "05_similarity.md")
    if text is None:
        return None
    summary = {}
    for row in table_dicts(text, SIM_SUMMARY_HEADER):
        summary[row["Model"]] = {
            "score": parse_pct(row.get("Similarity", "")), "status": row.get("Stability", ""),
            "runs": row.get("Runs", ""), "valid_runs": row.get("Complete runs", ""),
            "run_spread": parse_pts(row.get("Run spread", "")), "case_spread": row.get("Case spread", "n/a"),
            "median_run": row.get("Median run", "n/a"), "all_runs": row.get("All runs, missing = 0", "")}
    flags = []
    m = re.search(r"^## Flags\s*\n(.*?)(?=^## |\Z)", text, re.M | re.S)
    if m:
        flags = [l[2:].strip() for l in m.group(1).splitlines() if l.startswith("- ") and "None" not in l[:8]]
    case_header = next((split_cells(l) for l in text.splitlines() if l.startswith(SIM_CASE_HEADER)), [])
    return {"summary": summary, "cases": table_rows(text, SIM_CASE_HEADER), "case_header": case_header,
            "runs": table_dicts(text, SIM_RUN_HEADER), "flags": flags}


def parse_pts(t):
    try:
        return float(t)
    except ValueError:
        return None


def load_config():
    """The whole skill-eval/config.yaml as a dict (empty when it cannot be read)."""
    try:
        return yaml.safe_load(CONFIG_PATH.read_text(encoding="utf-8")) or {}
    except (OSError, yaml.YAMLError):
        return {}


def blocker_rows(structure_text):
    """[(what's wrong, suggested fix)] for the Blocker rows of the static report."""
    out = []
    for line in (structure_text or "").splitlines():
        if line.startswith("|"):
            c = split_cells(line)
            if len(c) >= 3 and c[1] == "Blocker":
                out.append((c[0], c[2]))
    return out


# ---------- reading a baseline report ----------

def sections_of(report_text):
    parts = re.split(r"^## (\d+)\. .*$", report_text, flags=re.M)
    return {int(parts[i]): parts[i + 1].strip() for i in range(1, len(parts), 2)}


def read_baseline(base_dir):
    path = Path(base_dir) / "detailed_final_report.md"
    text = read(path)
    if text is None:
        sys.exit(f"Error: {path} not found. Run skill-eval on the older version first.")
    sec = sections_of(text)
    runs = {}
    for cells in table_rows(sec.get(4, ""), "| Model used"):
        runs[cells[0]] = {"tokens": parse_tokens(cells[1]), "time": parse_time(cells[2]), "cost": parse_cost(cells[3])}
    m = re.search(r"Version:\s*`([^`]+)`", sec.get(2, ""))
    return {
        "version": m.group(1) if m else "unknown",
        "runs": runs,
        "similarity": {r["Model"].replace(" (recommended)", ""): parse_pct(r.get("Similarity", ""))
                       for r in table_dicts(sec.get(8, ""), SIM_SUMMARY_HEADER) if "Model" in r},
        "comparison": table_rows(sec.get(5, ""), "| Verified output"),
        "structure": sec.get(6, ""),
        "rubric": sec.get(7, ""),
    }


# ---------- rendering ----------

def chart(title, unit, models, old, new, key):
    def num(v):
        return 0 if v is None else round(v, 4) if key == "cost" else round(v)
    ymax = max([num(x) for x in old + new] + [1])
    ymax = int(ymax * 1.15) + 1
    return "\n".join([
        "```mermaid", "xychart-beta",
        f'    title "{title} - V1 (first bar) vs V2 (second bar)"',
        f"    x-axis [{', '.join(models)}]",
        f'    y-axis "{unit}" 0 --> {ymax}',
        f"    bar [{', '.join(str(num(x)) for x in old)}]",
        f"    bar [{', '.join(str(num(x)) for x in new)}]",
        "```",
    ])


def run_table(runs):
    lines = [RUN_HEADER, "| --- | ---: | ---: | ---: |"]
    for m, r in runs.items():
        lines.append(f"| {m} | {fmt_tokens(r['tokens'])} | {fmt_time(r['time'])} | {fmt_cost(r['cost'])} |")
    return lines


def compare_run_table(old_runs, new_runs, v1, v2):
    lines = [
        f"| Model | Tokens V1 ({v1}) | Tokens V2 ({v2}) | Tokens change | Time V1 | Time V2 | Time change "
        "| Cost V1 | Cost V2 | Cost change |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for m in new_runs:
        o, n = old_runs.get(m, {}), new_runs[m]
        ot, nt = o.get("tokens"), n["tokens"]
        os_, ns = o.get("time"), n["time"]
        oc, nc = o.get("cost"), n["cost"]
        lines.append(
            f"| {m} | {fmt_tokens(ot)} | {fmt_tokens(nt)} | {delta(ot, nt, lambda x: f'{x:,}')} "
            f"| {fmt_time(os_)} | {fmt_time(ns)} | {delta(os_, ns, fmt_time)} "
            f"| {fmt_cost(oc)} | {fmt_cost(nc)} | {delta(oc, nc, fmt_cost)} |"
        )
    return lines


def points_per_dollar(r):
    """Similarity points per dollar of a row (None when similarity or cost is missing, or the cost is 0)."""
    if r["similarity"] is None or not r["cost"]:
        return None
    return r["similarity"] / r["cost"]


def recommend(rows):
    """Pick the model to run the skill with. Pure function, no I/O.

    rows: dicts with model, similarity (0-100 or None; the mean over ALL runs of the model, a failed run or
    a missing case counting as 0), status (stability: stable, single run, unstable, insufficient or None),
    verdict (None, equivalent, minor gaps, disputed, major gaps), tokens, time, cost. Rule:
      1. drop models without similarity or cost, or with a "major gaps" verdict from both judges
         (disputed verdicts stay, flagged). Stability is not a filter: a failed run already costs the
         model its share of the similarity, and instability is reported next to the recommendation;
      2. value = similarity points per dollar = similarity / cost;
      3. recommend the model with the highest value (ties: more similar, then faster, then fewer tokens).
    """
    inf = float("inf")
    excluded, pool = [], []
    for r in rows:
        if r["similarity"] is None:
            excluded.append((r["model"], "no similarity measured"))
        elif not r["cost"]:
            excluded.append((r["model"], "cost unavailable"))
        elif r["verdict"] == "major gaps":
            excluded.append((r["model"], "verdict: major gaps"))
        else:
            pool.append(r)
    res = {"excluded": excluded, "pool": pool, "recommended": None, "best": None}
    scored = [r for r in rows if r["similarity"] is not None]
    res["highest_quality"] = (max(scored, key=lambda r: (r["similarity"], -VERDICTS.get(r["verdict"], 1)))
                              if scored else None)
    costed = [r for r in rows if r["cost"] is not None]
    res["cheapest"] = min(costed, key=lambda r: r["cost"]) if costed else None
    timed = [r for r in rows if r["time"] is not None]
    res["fastest"] = min(timed, key=lambda r: r["time"]) if timed else None
    if pool:
        res["best"] = max(pool, key=lambda r: r["similarity"])
        res["recommended"] = max(pool, key=lambda r: (
            points_per_dollar(r), r["similarity"], -(r["time"] if r["time"] is not None else inf),
            -(r["tokens"] if r["tokens"] is not None else inf)))
    return res


def percent_of(a, b):
    """'N%' for a / b, or '' when it cannot be computed."""
    return f"{a / b * 100:.0f}%" if a is not None and b else ""


def recommendation_rows(runs, sim, verdicts):
    rows = []
    for m, r in runs.items():
        v = verdicts.get(m)
        s = ((sim or {}).get("summary") or {}).get(m) or {}
        all_runs = parse_pct(s.get("all_runs", ""))
        rows.append({"model": m, "similarity": s.get("score") if all_runs is None else all_runs,
                     "status": s.get("status") or None,
                     "spread": s.get("run_spread"), "valid_runs": s.get("valid_runs", ""), "runs": s.get("runs", ""),
                     "verdict": v[0] if v else None, "verdict_reason": v[1] if v else "",
                     "tokens": r["tokens"], "time": r["time"], "cost": r["cost"]})
    return rows


def render_recommendation(rows, sim, base, number=8, stopped=False):
    """Lines of the model recommendation section, numbered `number` (8 in the detailed report, 4 in the short one)."""
    out = [f"## {number}. Model recommendation", ""]
    if stopped:
        return out + ["_Not run: the evaluation stopped at the structure check (see the blocking findings)._", ""]
    if sim is None:
        out += ["_No similarity data. Run the model runs (`scripts/run_skill.py`) and "
                "`python skill-eval/scripts/compute_similarity.py <skill_dir>`, then build the report again._", ""]
        return out
    res = recommend(rows)
    rec = res["recommended"]
    statuses = [r["status"] for r in rows if r["status"]]
    if statuses and not any(s in ("stable", "single run") for s in statuses):
        out += ["**Problem in the skill, not in a model:** no model gives stable results between repeated runs. "
                "When every model is unstable or fails runs, the cause is usually the skill (unclear steps, "
                "a result that depends on luck). Read the transcripts (`.jsonl` files) before relying on the "
                "recommendation below: it is only the best value among unreliable results.", ""]
    if rec is None:
        out += ["**No model can be recommended:** every model is excluded or has missing data (see below).", ""]
    else:
        others = sorted((r for r in res["pool"] if r is not rec), key=points_per_dollar, reverse=True)
        better_out = [(m, why) for m, why in res["excluded"]
                      if next(r for r in rows if r["model"] == m)["similarity"] is not None
                      and next(r for r in rows if r["model"] == m)["similarity"] > rec["similarity"]]
        why = (f"it gives the most similarity per dollar: {points_per_dollar(rec):.1f} points per $ "
               f"({fmt_pct(rec['similarity'])} for {fmt_cost(rec['cost'])})")
        if others:
            why += ", ahead of " + ", ".join(f"`{r['model']}` ({points_per_dollar(r):.1f})" for r in others)
        out += [f"**Recommended model: `{rec['model']}`.** {fmt_pct(rec['similarity'])} similar to the verified "
                f"outputs; per full run {fmt_tokens(rec['tokens'])} tokens, {fmt_time(rec['time'])}, "
                f"{fmt_cost(rec['cost'])}. Chosen because {why}.", ""]
        if better_out:
            out += ["Models with higher similarity that were not considered: " + "; ".join(
                f"`{m}` ({fmt_pct(next(r for r in rows if r['model'] == m)['similarity'])}, {why})"
                for m, why in better_out) + ".", ""]
        if rec["status"] in ("unstable", "insufficient"):
            spread = f" (run spread {rec['spread']:.1f} points)" if rec.get("spread") is not None else ""
            out += [f"**Note:** `{rec['model']}` is `{rec['status']}`{spread}. Its score already counts failed runs "
                    "as 0, but a single run can still land far from the mean.", ""]
        if rec["verdict"] == "disputed":
            out += [f"**Check by hand:** the judges disagree about `{rec['model']}`. {rec['verdict_reason']}", ""]
    if not any(r["verdict"] for r in rows):
        out += ["_No `Verdict:` line was found in the comparison reports, so no model was dropped for quality gaps._",
                ""]

    out += [f"| Model | Similarity | Quality verdict | Stability | Complete runs | Tokens | Time | Cost "
            f"| Similarity points per $ |",
            "| --- | ---: | --- | --- | ---: | ---: | ---: | ---: | ---: |"]
    for r in rows:
        ppd = points_per_dollar(r)
        per_dollar = f"{ppd:.1f}" if ppd is not None else "unavailable"
        verdict = VERDICT_LABELS.get(r["verdict"], "not given")
        mark = " (recommended)" if rec is not None and r["model"] == rec["model"] else ""
        done = f"{r['valid_runs']}/{r['runs']}" if r["runs"] else "n/a"
        out.append(f"| {r['model']}{mark} | {fmt_pct(r['similarity'])} | {verdict} | {r['status'] or 'n/a'} | {done} "
                   f"| {fmt_tokens(r['tokens'])} | {fmt_time(r['time'])} | {fmt_cost(r['cost'])} | {per_dollar} |")
    out += ["", "Similarity is the mean over all runs of the model: a failed run or a missing case counts as 0. "
            "Similarity points per $ = Similarity / Cost. Tokens, time and cost are means per full run "
            "(all inputs).", ""]

    out += [f"### {number}.1 At a glance", ""]
    for label, key, shown in (("Highest similarity", "highest_quality", lambda r: fmt_pct(r["similarity"])),
                              ("Cheapest", "cheapest", lambda r: fmt_cost(r["cost"])),
                              ("Fastest", "fastest", lambda r: fmt_time(r["time"]))):
        r = res[key]
        out.append(f"- {label}: `{r['model']}` ({shown(r)})" if r else f"- {label}: unavailable")
    best = res["best"]
    if rec and best and best["model"] != rec["model"]:
        costs = percent_of(rec["cost"], best["cost"])
        times = percent_of(rec["time"], best["time"])
        extra = ", ".join(x for x in ((f"{costs} of the cost" if costs else ""), (f"{times} of the time" if times else "")) if x)
        out.append(f"- Trade-off: `{best['model']}` is {best['similarity'] - rec['similarity']:.1f} points more similar "
                   f"than `{rec['model']}`, which needs" + (f" {extra} of `{best['model']}`." if extra else " less."))
    elif rec and best:
        out.append(f"- Trade-off: none among the qualifying models. `{rec['model']}` is both the most similar and "
                   "the best value.")
    ch = res["cheapest"]
    if rec and ch and ch["model"] != rec["model"] and ch in res["pool"] and rec["cost"]:
        out.append(f"- Cheaper option: `{ch['model']}` ({ch['cost'] / rec['cost'] * 100:.0f}% of the cost of "
                   f"`{rec['model']}`) is {rec['similarity'] - ch['similarity']:.1f} points less similar.")
    out.append("")
    if res["excluded"]:
        out += ["Not considered: " + "; ".join(f"`{m}` ({why})" for m, why in res["excluded"]) + ".", ""]
    reasons = [f"- `{r['model']}`: {r['verdict_reason']}" for r in rows if r["verdict_reason"]]
    if reasons:
        out += ["Verdicts from the comparison step:", ""] + reasons + [""]

    out += [f"### {number}.2 How the choice is made", "",
            "1. Drop models without similarity or cost, or with a `Major gaps` verdict from both judges. A `Disputed` "
            "verdict (judges disagree) keeps the model in and asks for a manual check.",
            "2. Similarity of a model is the mean over all its runs, a failed run counting as 0. Value = similarity / "
            "cost, in similarity points per $.",
            "3. Recommend the model with the highest value. Ties: more similar, then faster, then fewer tokens.",
            "4. Stability is not a filter, but it is reported. If no model is stable, the report names the skill as "
            "the likely problem.", ""]
    if base and base.get("similarity"):
        out += [f"### {number}.3 Similarity: V1 and V2", "",
                "| Model | Similarity V1 | Similarity V2 | Change (points) |", "| --- | ---: | ---: | ---: |"]
        for r in rows:
            o, n = base["similarity"].get(r["model"]), r["similarity"]
            chg = "n/a" if o is None or n is None else f"{n - o:+.1f}"
            out.append(f"| {r['model']} | {fmt_pct(o)} | {fmt_pct(n)} | {chg} |")
        out.append("")
    n_cases = len({c[0] for c in sim["cases"]})
    out += ["### Caveats", "",
            f"- Similarity is a proxy measured on {n_cases} case(s). It checks facts, wording and structure against "
            "the verified output. It does not replace reading the comparison notes.",
            "- With few cases and few repeats, a difference of a point or two in similarity is inside the noise."]
    return out + [""]


def render_stability(sim, runs):
    """Section 9 of the detailed report: stability between repeated runs and agent behaviour."""
    out = ["## 9. Run stability and behaviour", ""]
    if sim is None:
        return out + ["_No similarity data._", ""]
    out += ["Stability is judged on repeats of the same input: a model is unstable when one input gets very "
            "different similarity from one run to the next. Differences between inputs do not count.", "",
            "| Model | Runs | Complete runs | Similarity (complete runs) | Run spread (points) | Mean case spread (points) "
            "| Stability |", "| --- | ---: | ---: | ---: | ---: | ---: | --- |"]
    for m, s in sim["summary"].items():
        spread = "n/a" if s["run_spread"] is None else f"{s['run_spread']:.1f}"
        out.append(f"| {m} | {s['runs']} | {s['valid_runs']} | {fmt_pct(s['score'])} | {spread} | {s['case_spread']} "
                   f"| {s['status']} |")
    out.append("")
    if sim["runs"]:
        out += ["Similarity of each run (a missing case counts as 0 and makes the run incomplete):", "",
                "| Model | Run | Similarity | Status | Missing cases |", "| --- | ---: | ---: | --- | ---: |"]
        out += [f"| {r.get('Model', '')} | {r.get('Run', '')} | {r.get('Similarity', '')} | {r.get('Status', '')} "
                f"| {r.get('Missing cases', '')} |" for r in sim["runs"]]
        out.append("")
    behaviour = [(m, r["extra"]) for m, r in runs.items() if r.get("extra")]
    if behaviour:
        out += ["Agent behaviour from the run reports (means per full run; the transcripts are the `.jsonl` files "
                "next to the outputs):", "",
                "| Model | Failed cases | Turns | Tool calls | Skill loaded | Input tokens | Output tokens | Cache read tokens |",
                "| --- | ---: | ---: | ---: | --- | ---: | ---: | ---: |"]
        for m, e in behaviour:
            out.append(f"| {m} | {e.get('Failed cases', 'n/a')} | {e.get('Turns', 'n/a')} | {e.get('Tool calls', 'n/a')} "
                       f"| {e.get('Skill loaded', 'n/a')} | {e.get('Input tokens', 'n/a')} | {e.get('Output tokens', 'n/a')} "
                       f"| {e.get('Cache read tokens', 'n/a')} |")
        out.append("")
    out += ["Flags:", ""] + ([f"- {f}" for f in sim["flags"]] or ["- None."]) + [""]
    return out


def counts_line(text):
    m = re.search(r"(\d+) blocker\(s\), (\d+) warning\(s\), (\d+) info", text or "")
    return tuple(int(x) for x in m.groups()) if m else None


def collect(skill_dir, baseline_dir=None):
    """Everything both reports are built from."""
    meta = skill_meta(skill_dir)
    steps = Path(skill_dir) / "step_reports"
    structure = read(steps / "01_structure.md") or "_Not run._"
    runs = read_runs(skill_dir, meta)
    sim = read_similarity(skill_dir)
    blockers = blocker_rows(structure)
    return {
        "meta": meta, "structure": structure, "rubric": read(steps / "02_rubric.md") or "_Not run._",
        "runs": runs, "cmp_rows": read_comparison_rows(skill_dir), "sim": sim,
        "rec_rows": recommendation_rows(runs, sim, read_verdicts(skill_dir)),
        "base": read_baseline(baseline_dir) if baseline_dir else None, "blockers": blockers,
        "stopped": bool(blockers) and not runs and sim is None,
        "generated": (Path(skill_dir) / "evals" / "GENERATED.md").is_file(),
    }


def build_detailed(ctx):
    meta, runs, sim, base = ctx["meta"], ctx["runs"], ctx["sim"], ctx["base"]
    structure, rubric, cmp_rows = ctx["structure"], ctx["rubric"], ctx["cmp_rows"]
    v1, v2 = (base["version"] if base else None), meta["version"]

    out = [f"# Detailed Final Evaluation Report: {meta['name']}", ""]

    # 1. Summary
    out += ["## 1. Summary", ""]
    if ctx["stopped"]:
        out += [f"Evaluation of `{meta['name']}` version {v2} stopped at the structure check: "
                f"{len(ctx['blockers'])} blocking finding(s). Later steps did not run.", ""]
    elif base:
        shared = [m for m in runs if m in base["runs"]]
        out.append(f"Comparison of `{meta['name']}` version {v1} (V1) with version {v2} (V2). "
                   "Charts cover models that ran on both versions.")
        out.append("")
        if shared:
            for title, unit, key in (("Token usage", "tokens", "tokens"), ("Total cost", "USD", "cost"),
                                     ("Time spent", "seconds", "time")):
                out += [chart(title, unit, shared, [base["runs"][m][key] for m in shared],
                              [runs[m][key] for m in shared], key), ""]
        else:
            out += ["_No model ran on both versions, so there is nothing to chart._", ""]
    else:
        out += [f"Evaluation of `{meta['name']}` version {v2} on {len(runs)} model(s): "
                f"{', '.join(runs) or 'none'}.", ""]
    if sim is not None:
        rec = recommend(ctx["rec_rows"])["recommended"]
        out += [f"Recommended model: **{rec['model']}** (see section 8)." if rec
                else "No model could be recommended (see section 8).", ""]
    if ctx["generated"]:
        out += [f"Note: {GENERATED_NOTE}", ""]

    # 2, 3
    version_line = f"Version: `{v2}`" + (f" (compared with `{v1}`)" if base else "")
    out += ["## 2. Skill name", "", f"Name: `{meta['name']}`  ", version_line, ""]
    out += ["## 3. Skill description", "", meta["description"] or "_No description found._", ""]

    # 4. Run results
    out += ["## 4. Run results", ""]
    if base:
        out += compare_run_table(base["runs"], runs, v1, v2) + [""]
        out += [f"Current version ({v2}):", ""]
    out += run_table(runs) + [""]

    # 5. Output comparison
    out += ["## 5. Output comparison", "", COMPARE_HEADER, "| --- | --- | --- | --- | --- |"]
    out += cmp_rows or ["| _none_ | | | | |"]
    out.append("")
    if sim is not None and sim["cases"]:
        out += ["Similarity per case, mean over the complete runs (details in `step_reports/05_similarity.md`):", "",
                "| " + " | ".join(sim["case_header"]) + " |",
                "| --- | --- |" + " ---: |" * (len(sim["case_header"]) - 2)]
        out += ["| " + " | ".join(c) + " |" for c in sim["cases"]]
        out.append("")
    if base:
        old_notes = {(c[0], c[2]): c[4] for c in base["comparison"] if len(c) >= 5}
        out += ["Notes side by side:", "", f"| Verified output | Model | Notes V1 ({v1}) | Notes V2 ({v2}) |",
                "| --- | --- | --- | --- |"]
        for row in cmp_rows:
            c = split_cells(row)
            if len(c) >= 5:
                out.append(f"| {c[0]} | {c[2]} | {old_notes.get((c[0], c[2]), 'n/a')} | {c[4]} |")
        out.append("")

    # 6. Structure check
    out += ["## 6. Skill structure check", ""]
    if base:
        o, n = counts_line(base["structure"]), counts_line(structure)
        if o and n:
            out += ["| Severity | V1 | V2 | Change |", "| --- | ---: | ---: | ---: |"]
            for label, a, b in zip(("Blocker", "Warning", "Info"), o, n):
                out.append(f"| {label} | {a} | {b} | {b - a:+d} |")
            out.append("")
    out += [demote(structure), ""]

    # 7. Rubric review
    out += ["## 7. Skill rubric review", ""]
    if base:
        out += [f"### 7.1 Current version ({v2})", "", demote(rubric, 3), "",
                f"### 7.2 Previous version ({v1})", "", demote(base["rubric"], 1), ""]
    else:
        out += [demote(rubric), ""]

    # 8. Model recommendation, 9. Stability
    out += render_recommendation(ctx["rec_rows"], sim, base, 8, ctx["stopped"])
    out += render_stability(sim, runs)
    return "\n".join(out).rstrip() + "\n"


def build_short(ctx):
    """final_report.md: Summary, Skill name, Skill description, Model recommendation, and the blocking findings."""
    meta, runs, sim = ctx["meta"], ctx["runs"], ctx["sim"]
    out = [f"# Final Evaluation Report: {meta['name']}", "", "## 1. Summary", ""]
    if ctx["stopped"]:
        out += [f"Evaluation of `{meta['name']}` version {meta['version']} stopped at the structure check: "
                f"{len(ctx['blockers'])} blocking finding(s) (section 5). Fix them and run the evaluation again; "
                "the rubric review and the model runs did not run.", ""]
    else:
        out += [f"Evaluation of `{meta['name']}` version {meta['version']} on {len(runs)} model(s): "
                f"{', '.join(runs) or 'none'}.", ""]
        if sim is not None:
            rec = recommend(ctx["rec_rows"])["recommended"]
            out += [f"Recommended model: **{rec['model']}** (section 4)." if rec
                    else "No model could be recommended (section 4).", ""]
        if ctx["blockers"]:
            out += [f"The structure check reported {len(ctx['blockers'])} blocking finding(s) (section 5).", ""]
    if ctx["generated"]:
        out += [f"Note: {GENERATED_NOTE}", ""]
    out += ["## 2. Skill name", "", f"Name: `{meta['name']}`  ", f"Version: `{meta['version']}`", "",
            "## 3. Skill description", "", meta["description"] or "_No description found._", ""]
    out += render_recommendation(ctx["rec_rows"], sim, ctx["base"], 4, ctx["stopped"])
    if ctx["blockers"]:
        out += ["## 5. Blocking structure findings", "", "Only the blocking (Blocker) findings of the structure check. "
                "The full check is in the detailed report.", "", "| What's wrong | Suggested fix |", "| --- | --- |"]
        out += [f"| {w.replace('|', chr(92) + '|')} | {f.replace('|', chr(92) + '|')} |" for w, f in ctx["blockers"]]
        out.append("")
    out += ["Full report: `detailed_final_report.md`.", ""]
    return "\n".join(out).rstrip() + "\n"


def build(skill_dir, baseline_dir=None):
    """The detailed report (kept for callers of the old single report)."""
    return build_detailed(collect(skill_dir, baseline_dir))


def main():
    args = sys.argv[1:]

    def opt(name):
        if name in args:
            i = args.index(name)
            if i + 1 >= len(args):
                sys.exit(f"Error: {name} needs a value.")
            return args[i + 1]

    if not args or args[0].startswith("--"):
        sys.exit("Usage: python build_final_report.py <skill_dir> [--baseline <older_skill_dir>] [--out <path>]")
    skill_dir = args[0]
    if not (Path(skill_dir) / "SKILL.md").is_file():
        sys.exit(f"Error: no SKILL.md in {skill_dir}")
    ctx = collect(skill_dir, opt("--baseline"))
    detailed = Path(opt("--out") or Path(skill_dir) / "detailed_final_report.md")
    short = detailed.parent / "final_report.md"
    detailed.parent.mkdir(parents=True, exist_ok=True)
    detailed.write_text(build_detailed(ctx), encoding="utf-8")
    short.write_text(build_short(ctx), encoding="utf-8")
    print(f"Wrote {short}")
    print(f"Wrote {detailed}")


if __name__ == "__main__":
    main()
